using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;


namespace Content.Client._Lust.Canvas;

[GenerateTypedNameReferences]
public sealed partial class CanvasToolboxWindow : BaseWindow
{
    private CanvasToolState? _tools;
    private readonly ButtonGroup _toolGroup = new(false);
    private readonly StyleBoxFlat _previewStyle = new() { BackgroundColor = Color.Black };
    private bool _wired;
    private ColorSwatch[] _swatches = [];

    public CanvasToolboxWindow()
    {
        RobustXamlLoader.Load(this);
        SizeLabel.Text = Loc.GetString("lust-canvas-size", ("size", 2));

        PenButton.Group = _toolGroup;
        BrushButton.Group = _toolGroup;
        FillButton.Group = _toolGroup;
        EraserButton.Group = _toolGroup;
        EyedropperButton.Group = _toolGroup;

        PenButton.OnPressed += _ => SetTool(CanvasTool.Pen);
        BrushButton.OnPressed += _ => SetTool(CanvasTool.Brush);
        FillButton.OnPressed += _ => SetTool(CanvasTool.Fill);
        EraserButton.OnPressed += _ => SetTool(CanvasTool.Eraser);
        EyedropperButton.OnPressed += _ => SetTool(CanvasTool.Eyedropper);

        SizeSlider.OnValueChanged += _ =>
        {
            if (_tools == null)
                return;
            _tools.Size = (int) SizeSlider.Value;
            SizeLabel.Text = Loc.GetString("lust-canvas-size", ("size", _tools.Size));
            _tools.Touch();
        };

        Preview.PanelOverride = _previewStyle;

        _swatches = new[]
        {
            Swatch0, Swatch1, Swatch2, Swatch3, Swatch4,
            Swatch5, Swatch6, Swatch7, Swatch8, Swatch9,
            Swatch10, Swatch11,
        };

        SvSquare.Changed += RefreshFromPicker;
        HueStrip.Changed += OnHueChanged;
        OpacitySlider.OnValueChanged += _ => RefreshFromPicker();
        HexEdit.OnTextEntered += _ => ApplyHex();
    }

    public void SetTools(CanvasToolState tools)
    {
        _tools = tools;

        if (!_wired)
        {
            _wired = true;
            tools.Changed += RefreshColorWidgets;
            for (var i = 0; i < _swatches.Length; i++)
            {
                var slot = i;
                _swatches[slot].Picked += () => SelectSlot(slot);
            }
        }

        SizeSlider.Value = tools.Size;
        SizeLabel.Text = Loc.GetString("lust-canvas-size", ("size", tools.Size));
        GetToolButton(tools.Tool).Pressed = true;

        RefreshColorWidgets();
        RefreshFromPicker();
    }

    /// <summary>
    /// Функция выбора активной ячейки цвета
    /// </summary>
    private void SelectSlot(int slot)
    {
        if (_tools == null || slot < 0 || slot >= _tools.SavedColors.Count)
            return;

        _tools.SelectedSlot = slot;
        var color = _tools.SavedColors[slot];
        _tools.Color = color;
        _tools.Opacity = color.A;
        _tools.Touch();
    }

    /// <summary>
    /// Обновление визуала виджета
    /// </summary>
    private void RefreshColorWidgets()
    {
        if (_tools == null)
            return;

        // Любое изменение цвета (квадрат, пипетка, hex) пишется в выбранную ячейку
        _tools.SavedColors[_tools.SelectedSlot] = _tools.Color;
        for (var i = 0; i < _swatches.Length && i < _tools.SavedColors.Count; i++)
        {
            _swatches[i].SetColor(_tools.SavedColors[i]);
            _swatches[i].SetSelected(i == _tools.SelectedSlot);
        }

        var hsv = Color.ToHsv(_tools.Color);
        if (hsv.Y > 0.02f && hsv.Z > 0.02f)
        {
            HueStrip.SetHue(hsv.X);
            SvSquare.SetHsv(hsv.X, hsv.Y, hsv.Z);
        }
        else
        {
            SvSquare.SetHsv(HueStrip.H, hsv.Y, hsv.Z);
        }
        OpacitySlider.Value = _tools.Color.A * 100f;
        ApplyPreview(_tools.Color, updateHex: true);
    }

    private void OnHueChanged()
    {
        SvSquare.SetHue(HueStrip.H);
        RefreshFromPicker();
    }

    private void RefreshFromPicker()
    {
        if (_tools == null)
            return;

        var alpha = OpacitySlider.Value / 100f;
        var color = Color.FromHsv(new Vector4(HueStrip.H, SvSquare.S, SvSquare.V, alpha));
        ApplyColor(color, updateHex: true);
    }

    private void ApplyHex()
    {
        if (_tools == null)
            return;

        var text = HexEdit.Text.Trim().TrimStart('#');
        if (text.Length != 6 && text.Length != 8)
            return;

        if (!TryParseHexByte(text, 0, out var r)
            || !TryParseHexByte(text, 2, out var g)
            || !TryParseHexByte(text, 4, out var b))
            return;

        byte a = 255;
        if (text.Length == 8 && !TryParseHexByte(text, 6, out a))
            return;

        var color = new Color(r, g, b, a);
        var hsv = Color.ToHsv(color);
        HueStrip.SetHue(hsv.X);
        SvSquare.SetHsv(hsv.X, hsv.Y, hsv.Z);
        OpacitySlider.Value = a / 255f * 100f;
        ApplyColor(color, updateHex: false);
    }

    private static bool TryParseHexByte(string text, int start, out byte value)
    {
        value = 0;
        if (start + 2 > text.Length)
            return false;

        var hi = HexNibble(text[start]);
        var lo = HexNibble(text[start + 1]);
        if (hi < 0 || lo < 0)
            return false;

        value = (byte) ((hi << 4) | lo);
        return true;
    }

    private static int HexNibble(char c)
    {
        if (c >= '0' && c <= '9')
            return c - '0';
        if (c >= 'a' && c <= 'f')
            return c - 'a' + 10;
        if (c >= 'A' && c <= 'F')
            return c - 'A' + 10;
        return -1;
    }

    private void ApplyColor(Color color, bool updateHex)
    {
        if (_tools == null)
            return;

        _tools.Color = color;
        _tools.Opacity = color.A;
        _tools.Touch();

        ApplyPreview(color, updateHex);
    }

    private void ApplyPreview(Color color, bool updateHex = true)
    {
        _previewStyle.BackgroundColor = color;
        if (updateHex)
            HexEdit.Text = $"#{color.RByte:X2}{color.GByte:X2}{color.BByte:X2}";
    }

    private Button GetToolButton(CanvasTool tool)
    {
        return tool switch
        {
            CanvasTool.Pen => PenButton,
            CanvasTool.Brush => BrushButton,
            CanvasTool.Fill => FillButton,
            CanvasTool.Eraser => EraserButton,
            CanvasTool.Eyedropper => EyedropperButton,
            _ => PenButton,
        };
    }

    private void SetTool(CanvasTool tool)
    {
        if (_tools == null)
            return;
        _tools.Tool = tool;
        _tools.Touch();
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        return relativeMousePos.Y < 34f ? DragMode.Move : DragMode.None;
    }
}
