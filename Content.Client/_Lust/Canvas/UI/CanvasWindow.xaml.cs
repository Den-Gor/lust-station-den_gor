using Content.Client._Lust.Canvas.UI.Elements;
using Content.Shared._Lust.Canvas;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Lust.Canvas.UI;

[GenerateTypedNameReferences]
public sealed partial class CanvasWindow :  DefaultWindow
{
    private CanvasControl? _canvas;
    private CanvasClientSystem? _systems;
    private BoundUserInterface? _boundUserInterface;
    private EntityUid _paper;



    public CanvasWindow()
    {
        RobustXamlLoader.Load(this);
        Title = Loc.GetString("lust-canvas-window-title");
    }

    /// <summary>
    /// Загрузка меню тулбокса
    /// </summary>
    /// <param name="tools"></param>
    public void SetTools(CanvasToolState  tools)
    {
        _canvas = new CanvasControl(tools);
        CanvasHost.AddChild(_canvas);
        ToolsButton.OnPressed += _ => _systems?.ToggleToolbox();
        UndoButton.OnPressed += _ => _canvas?.Undo();
        SaveButton.OnPressed += _ =>
        {
            if (_canvas?.HasUnchangedLoadedImage == true)
            {
                _boundUserInterface?.SendMessage(new CanvasOpenViewMessage());
                return;
            }

            var png = _canvas?.Save();
            if (png == null)
                return;
            _systems?.SendSave(_paper, png);
        };
    }

    public void SetSystems(CanvasClientSystem systems)
    {
        _systems = systems;
    }

    public void SetBoundUserInterface(BoundUserInterface boundUserInterface)
    {
        _boundUserInterface = boundUserInterface;
    }

    public void SetPaper(EntityUid paper)
    {
        _paper = paper;
    }

    public void LoadImage(byte[] data)
    {
        _canvas?.LoadImage(data);
    }

    public void SetImageLoadFailed()
    {
        _canvas?.SetLoading(true);
    }

    public void SetLoading(bool loading)
    {
        _canvas?.SetLoading(loading);
    }
}
