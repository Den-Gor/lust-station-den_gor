using Content.Client._Sunrise;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;

namespace Content.Client._Lust.Canvas.UI;

[GenerateTypedNameReferences]
public sealed partial class CanvasViewWindow : DefaultWindow
{
    [Dependency] private NetTexturesManager _netTextures = default!;

    private string? _path;

    public CanvasViewWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        // Ресурс приезжает асинхронно, поэтому ждём сигнала о готовности.
        _netTextures.ResourceLoaded += OnResourceLoaded;
    }

    /// <summary>
    /// Показывает рисунок по пути к зарегистрированной сетевой текстуре.
    /// </summary>
    public void SetImage(string path)
    {
        _path = path;

        if (_netTextures.EnsureResource(path))
            UpdateTexture();
    }

    private void OnResourceLoaded(string path)
    {
        if (path == _path)
            UpdateTexture();
    }

    private void UpdateTexture()
    {
        if (_netTextures.TryGetTexture(_path!, out var texture) && texture != null)
            Image.Texture = texture;
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (disposing)
            _netTextures.ResourceLoaded -= OnResourceLoaded;
    }
}