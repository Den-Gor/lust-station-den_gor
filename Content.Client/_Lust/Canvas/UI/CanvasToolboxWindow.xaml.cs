using System.Numerics;
using Content.Client._Lust.Canvas.UI.Elements;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;


namespace Content.Client._Lust.Canvas.UI;


/// <summary>
/// UI тулбокса с инструментами настройкой размера и прозрачности, а также палитрой цвета
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CanvasToolboxWindow : BaseWindow
{
    private CanvasToolState? _tools;
    private readonly ButtonGroup _toolGroup = new(false);
    private readonly StyleBoxFlat _previewStyle = new() { BackgroundColor = Color.Black };
    private bool _wired;
    private readonly List<ColorSwatch> _swatches = [];

    public CanvasToolboxWindow()
    {
        RobustXamlLoader.Load(this);

        PenButton.Group = _toolGroup;
        BrushButton.Group = _toolGroup;
        FillButton.Group = _toolGroup;
        EraserButton.Group = _toolGroup;
        EyedropperButton.Group = _toolGroup;

        PenButton.OnPressed += _ => SetTool(CanvasTool.Pen);
        BrushButton.OnPressed += _ => SetTool(CanvasTool.Brush);
        FillButton.OnPressed += _ => SetTool(CanvasTool.Fill);
        EraserButton.OnPressed += _ => SetTool(CanvasTool.Eraser);
        EyedropperButton.OnPressed += _ => SetTool(CanvasTool.Eyedropper);

        SizeSlider.OnValueChanged += _ =>
        {
            if (_tools == null)
                return;
            _tools.Size = (int) SizeSlider.Value;
            SizeLabel.Text = Loc.GetString("lust-canvas-size", ("size", _tools.Size));
        };

        Preview.PanelOverride = _previewStyle;

        Picker.HsvChanged += (h, s, v) => _tools?.SetHsvSelection(h, s, v);
        OpacitySlider.OnValueChanged += _ => OnOpacityMoved();
        HexEdit.OnTextEntered += _ => ApplyHex();
        OnClose += UnwireTools;
    }

    private void UnwireTools()
    {
        if (_tools != null)
            _tools.Changed -= Refresh;
    }

    /// <summary>
    /// Функция загрузки текущего инструмента, его настроек и цвета
    /// </summary>
    /// <param name="tools"></param>
    public void SetTools(CanvasToolState tools)
    {
        if (_tools != null)
            _tools.Changed -= Refresh;

        _tools = tools;
        _tools.Changed += Refresh;
        SizeSlider.MinValue = tools.Config.MinBrushSize;
        SizeSlider.MaxValue = tools.Config.MaxBrushSize;
        SizeSlider.SetValueWithoutEvent(tools.Size);

        if (!_wired)
        {
            _wired = true;
            for (var i = 0; i < tools.Palette.Count; i++)
            {
                var slot = i;
                var swatch = new ColorSwatch();
                swatch.Selected += () => SelectSlot(slot);
                SwatchGrid.AddChild(swatch);
                _swatches.Add(swatch);
            }
        }

        SizeLabel.Text = Loc.GetString("lust-canvas-size", ("size", tools.Size));
        GetToolButton(tools.Tool).Pressed = true;

        Refresh();
    }

    /// <summary>
    /// Установка в tools номера выбранного ColorSwatch
    /// </summary>
    /// <param name="slot"></param>
    private void SelectSlot(int slot)
    {
        _tools?.SelectSlot(slot);
    }

    /// <summary>
    /// Событие изменения прозрачности
    /// </summary>
    private void OnOpacityMoved()
    {
        _tools?.SetOpacity(OpacitySlider.Value / 100f);
    }

    /// <summary>
    /// Пересбор визуала всей UI
    /// </summary>
    private void Refresh()
    {
        if (_tools == null)
            return;

        var hsv = _tools.SelectedHsv;
        Picker.SetHsv(hsv.X, hsv.Y, hsv.Z);
        OpacitySlider.SetValueWithoutEvent(_tools.Opacity * 100f);
        UpdateSwatches();
        ApplyPreview(_tools.BrushColor);
    }

    /// <summary>
    /// Пересбор всех ColorSwatch
    /// </summary>
    private void UpdateSwatches()
    {
        if (_tools == null)
            return;
        for (var i = 0; i < _swatches.Count && i < _tools.Palette.Count; i++)
        {
            _swatches[i].SetColor(_tools.Palette[i].Color);
            _swatches[i].Select(i == _tools.SelectedIndex);
        }
    }

    /// <summary>
    /// Событие установки цвета из текстового поля Hex
    /// </summary>
    private void ApplyHex()
    {
        if (_tools == null)
            return;

        var text = HexEdit.Text.Trim().TrimStart('#');
        if (text.Length != 6)
            return;

        if (!TryParseHexByte(text, 0, out var r)
            || !TryParseHexByte(text, 2, out var g)
            || !TryParseHexByte(text, 4, out var b))
            return;

        _tools.SetExternal(new Color(r, g, b));
    }

    private static bool TryParseHexByte(string text, int start, out byte value)
    {
        value = 0;
        if (start + 2 > text.Length)
            return false;

        var hi = HexNibble(text[start]);
        var lo = HexNibble(text[start + 1]);
        if (hi < 0 || lo < 0)
            return false;

        value = (byte) ((hi << 4) | lo);
        return true;
    }

    private static int HexNibble(char c)
    {
        if (c >= '0' && c <= '9')
            return c - '0';
        if (c >= 'a' && c <= 'f')
            return c - 'a' + 10;
        if (c >= 'A' && c <= 'F')
            return c - 'A' + 10;
        return -1;
    }
    /// <summary>
    /// Установка визуализации выбранного Hex
    /// </summary>
    /// <param name="color"></param>
    private void ApplyPreview(Color color)
    {
        _previewStyle.BackgroundColor = color;
        HexEdit.Text = $"#{color.RByte:X2}{color.GByte:X2}{color.BByte:X2}";
    }

    /// <summary>
    /// Функция возрващает выбранную кнопку инструментов
    /// </summary>
    /// <param name="tool"></param>
    /// <returns></returns>
    private Button GetToolButton(CanvasTool tool)
    {
        return tool switch
        {
            CanvasTool.Pen => PenButton,
            CanvasTool.Brush => BrushButton,
            CanvasTool.Fill => FillButton,
            CanvasTool.Eraser => EraserButton,
            CanvasTool.Eyedropper => EyedropperButton,
            _ => PenButton,
        };
    }

    /// <summary>
    /// Устанавливает выбранный инструмент
    /// </summary>
    /// <param name="tool"></param>
    private void SetTool(CanvasTool tool)
    {
        if (_tools == null)
            return;
        _tools.Tool = tool;
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        return relativeMousePos.Y < 34f ? DragMode.Move : DragMode.None;
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        UnwireTools();
    }
}
