using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;


namespace Content.Client._Lust.Canvas;

[GenerateTypedNameReferences]
public sealed partial class CanvasWindow : DefaultWindow
{
    private CanvasControl? _canvas;
    private CanvasClientSystem? _systems;

    public CanvasWindow()
    {
        RobustXamlLoader.Load(this);
        Title = Loc.GetString("lust-canvas-window-title");
    }

    public void SetTools(CanvasToolState tools)
    {
        _canvas = new CanvasControl(tools);
        CanvasHost.AddChild(_canvas);
        UndoButton.OnPressed += _ => _canvas?.Undo();
        ToolsButton.OnPressed += _ => _systems?.ToggleToolbox();
    }

    public void SetSystems(CanvasClientSystem systems)
    {
        _systems = systems;
    }
}
